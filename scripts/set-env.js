const fs = require('node:fs');
const path = require('node:path');

try {
  require('dotenv').config({ path: path.join(__dirname, '../.env') });
} catch {
  // dotenv optional if environment variables are injected by CI/hosting
}

const envDir = path.join(__dirname, '../src/environments');
fs.mkdirSync(envDir, { recursive: true });

const supabaseUrl = (process.env.SUPABASE_URL || '').trim();
const supabaseAnonKey = (process.env.SUPABASE_ANON_KEY || '').trim();
const paystackPublicKey = (process.env.PAYSTACK_PUBLIC_KEY || 'pk_test_beautiva_demo').trim();
const adminEmails = (process.env.SUPER_ADMIN_EMAILS || 'admin@beautiva.ng')
  .split(',')
  .map((e) => e.trim().toLowerCase())
  .filter(Boolean);

const makeContent = (production) => `// Auto-generated by scripts/set-env.js from .env
export const environment = {
  production: ${production},
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  paystackPublicKey: ${JSON.stringify(paystackPublicKey)},
  superAdminEmails: ${JSON.stringify(adminEmails)},
};
`;

fs.writeFileSync(path.join(envDir, 'environment.ts'), makeContent(true));
fs.writeFileSync(path.join(envDir, 'environment.development.ts'), makeContent(false));
console.log(
  `[set-env] Generated src/environments/environment.ts (Supabase ${
    supabaseUrl && supabaseAnonKey ? 'configured' : 'not yet configured — running in fallback mode'
  })`,
);

